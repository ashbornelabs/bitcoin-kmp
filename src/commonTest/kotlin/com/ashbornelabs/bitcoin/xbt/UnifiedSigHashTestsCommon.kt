package com.ashbornelabs.bitcoin.xbt

import fr.acinq.secp256k1.Hex
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.long
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertFalse
import kotlin.test.assertNotEquals
import kotlin.test.assertTrue

class UnifiedSigHashTestsCommon {
    private val priv = PrivateKey(ByteVector32("0101010101010101010101010101010101010101010101010101010101010101"))
    private val pub = priv.publicKey()
    private val p2wshScript = listOf(OP_PUSHDATA(pub), OP_CHECKSIG)
    private val tapscriptKey = PrivateKey(ByteVector32("0202020202020202020202020202020202020202020202020202020202020202"))
    private val tapleaf = ScriptTree.Leaf(listOf(OP_PUSHDATA(tapscriptKey.xOnlyPublicKey().value), OP_CHECKSIG))

    /** A transaction with one output per script type: P2PKH, P2WPKH, P2WSH, P2TR key path and P2TR script path. */
    private val parentTx = Transaction(
        version = 2,
        txIn = listOf(TxIn(OutPoint(Block.LivenetGenesisBlock.tx.first(), 0), TxIn.SEQUENCE_FINAL)),
        txOut = listOf(
            TxOut(10_000.sat(), Script.pay2pkh(pub)),
            TxOut(20_000.sat(), Script.pay2wpkh(pub)),
            TxOut(30_000.sat(), Script.pay2wsh(p2wshScript)),
            TxOut(40_000.sat(), Script.pay2tr(priv.xOnlyPublicKey(), Crypto.TaprootTweak.KeyPathTweak)),
            TxOut(50_000.sat(), Script.pay2tr(priv.xOnlyPublicKey(), tapleaf)),
        ),
        lockTime = 0
    )
    private val inputs = parentTx.txOut
    private val unsignedTx = Transaction(
        version = 2,
        txIn = inputs.indices.map { TxIn(OutPoint(parentTx, it.toLong()), TxIn.SEQUENCE_FINAL) },
        txOut = listOf(TxOut(140_000.sat(), Script.pay2wpkh(pub))),
        lockTime = 0
    )

    /**
     * Test vectors from Bitcoin Knots `src/test/data/unified_sighash.json` (tag v29.4.1.knots20260508), generated by an
     * independent Python implementation. Each vector is [scriptCode, rawTx (no witness), inIdx, hashType, scriptType,
     * spentOutputs, sighash], where sighash holds the raw hash bytes. Tapscript vectors have no annex and no OP_CODESEPARATOR.
     */
    @Test
    fun `knots test vectors`() {
        val vectors = TestHelpers.readResourceAsJson("data/unified_sighash.json").jsonArray.drop(1)
        val checked = IntArray(4)
        vectors.forEach { vector ->
            val fields = vector.jsonArray
            val scriptCode = Hex.decode(fields[0].jsonPrimitive.content)
            val tx = Transaction.read(fields[1].jsonPrimitive.content)
            val inputIndex = fields[2].jsonPrimitive.int
            val sighashType = fields[3].jsonPrimitive.int
            val scriptType = fields[4].jsonPrimitive.int
            val spentOutputs = fields[5].jsonArray.map { TxOut(Satoshi(it.jsonArray[0].jsonPrimitive.long), ByteVector(it.jsonArray[1].jsonPrimitive.content)) }
            val expected = ByteVector32(fields[6].jsonPrimitive.content)
            val sigVersion = listOf(SigVersion.SIGVERSION_BASE, SigVersion.SIGVERSION_WITNESS_V0, SigVersion.SIGVERSION_TAPROOT, SigVersion.SIGVERSION_TAPSCRIPT)[scriptType]
            val tapleaf = if (sigVersion == SigVersion.SIGVERSION_TAPSCRIPT) ScriptTree.Leaf(ByteVector(scriptCode), Script.TAPROOT_LEAF_TAPSCRIPT).hash() else null
            val sighash = tx.hashForSigningUnified(inputIndex, spentOutputs, sighashType, sigVersion, scriptCode, tapleaf)
            assertEquals(expected, sighash, "vector $vector")
            checked[scriptType]++
        }
        // bare, segwit v0, taproot and tapscript vectors
        assertEquals(listOf(76, 66, 12, 12), checked.toList())
    }

    @Test
    fun `commits to every spent output`() {
        val sighashType = SigHash.SIGHASH_ALL_UNIFIED
        val scriptCode = Script.write(Script.pay2pkh(pub))
        val otherInputs = inputs.toMutableList().also { it[0] = it[0].copy(amount = it[0].amount + 1.sat()) }
        // The unified message commits to the amount of every input (CVE-2020-14199), BIP 143 only to the one being signed.
        assertNotEquals(
            unsignedTx.hashForSigningUnified(1, inputs, sighashType, SigVersion.SIGVERSION_WITNESS_V0, scriptCode),
            unsignedTx.hashForSigningUnified(1, otherInputs, sighashType, SigVersion.SIGVERSION_WITNESS_V0, scriptCode)
        )
        assertTrue(
            unsignedTx.hashForSigning(1, scriptCode, SigHash.SIGHASH_ALL, inputs[1].amount, SigVersion.SIGVERSION_WITNESS_V0)
                .contentEquals(unsignedTx.hashForSigning(1, scriptCode, SigHash.SIGHASH_ALL, otherInputs[1].amount, SigVersion.SIGVERSION_WITNESS_V0))
        )
        // The unified message requires every spent output.
        assertFailsWith<IllegalArgumentException> { unsignedTx.hashForSigningUnified(1, inputs.take(2), sighashType, SigVersion.SIGVERSION_WITNESS_V0, scriptCode) }
    }

    @Test
    fun `hash type rules`() {
        // SIGHASH_DEFAULT cannot be combined with the unified bit: opted-in taproot signatures always have a hash type byte.
        assertFailsWith<IllegalArgumentException> { unsignedTx.hashForSigningUnified(3, inputs, SigHash.SIGHASH_UNIFIED, SigVersion.SIGVERSION_TAPROOT) }
        // Taproot keeps refusing hash types that BIP 341 does not define, pre-segwit and segwit v0 read them as SIGHASH_ALL.
        assertFailsWith<IllegalArgumentException> { unsignedTx.hashForSigningUnified(3, inputs, 0x24, SigVersion.SIGVERSION_TAPROOT) }
        unsignedTx.hashForSigningUnified(1, inputs, 0x24, SigVersion.SIGVERSION_WITNESS_V0, Script.write(Script.pay2pkh(pub)))
        // There is no special value for SIGHASH_SINGLE without a corresponding output.
        val single = SigHash.SIGHASH_SINGLE or SigHash.SIGHASH_UNIFIED
        unsignedTx.hashForSigningUnified(0, inputs, single, SigVersion.SIGVERSION_BASE, Script.write(Script.pay2pkh(pub)))
        assertFailsWith<IllegalArgumentException> { unsignedTx.hashForSigningUnified(1, inputs, single, SigVersion.SIGVERSION_WITNESS_V0, Script.write(Script.pay2pkh(pub))) }
        // The unified message is only defined for signatures that opt in.
        assertFailsWith<IllegalArgumentException> { unsignedTx.hashForSigningUnified(1, inputs, SigHash.SIGHASH_ALL, SigVersion.SIGVERSION_WITNESS_V0) }
    }

    @Test
    fun `signing and encoding rules`() {
        // Signing a legacy message with the unified bit set would produce a signature that is invalid after the fork.
        assertFailsWith<IllegalArgumentException> {
            unsignedTx.signInput(1, Script.pay2pkh(pub), SigHash.SIGHASH_ALL_UNIFIED, inputs[1].amount, SigVersion.SIGVERSION_WITNESS_V0, priv)
        }
        val sig = Hex.decode("3006020101020101")
        val unifiedFlags = ScriptFlags.SCRIPT_VERIFY_STRICTENC or ScriptFlags.SCRIPT_VERIFY_UNIFIED_SIGHASH
        assertTrue(Crypto.isDefinedHashTypeSignature(sig + 0x01))
        assertFalse(Crypto.isDefinedHashTypeSignature(sig + 0x21))
        assertFalse(Crypto.isDefinedHashTypeSignature(sig + 0x21, ScriptFlags.SCRIPT_VERIFY_STRICTENC))
        assertTrue(Crypto.isDefinedHashTypeSignature(sig + 0x21, unifiedFlags))
        assertTrue(Crypto.isDefinedHashTypeSignature(sig + 0xa3.toByte(), unifiedFlags))
        assertFalse(Crypto.isDefinedHashTypeSignature(sig + 0x24, unifiedFlags))
    }
}
